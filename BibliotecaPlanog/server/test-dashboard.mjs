// Pure dashboard calculations. Run: node github-export/server/test-dashboard.mjs
import {createRequire} from 'node:module';
import {readFileSync,existsSync} from 'node:fs';
import assert from 'node:assert/strict';
const ts=createRequire(new URL('../source/package.json',import.meta.url))('typescript');
const src=existsSync(new URL('../src/',import.meta.url))?'../src/':'../source/src/';
const load=async name=>{const source=readFileSync(new URL(src+name,import.meta.url),'utf8');const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});return import('data:text/javascript;base64,'+Buffer.from(compiled.outputText).toString('base64'));};
const {progress,effectiveStatus,moveSibling,descendants,depthOf}=await load('dashboard-model.ts');
const {checklistTemplate}=await load('dashboard-template.ts');
const task=(id,parent_id,status='Pendiente')=>({id,parent_id,status,title:id,owner:'',due:'',notes:''});
const items=[task('stage',null),task('finished','stage','Terminado'),task('branch','stage'),task('child','branch','Bloqueado'),task('na','branch','No aplica')];
assert.equal(progress(items).applicable,2);
assert.equal(progress(items).done,1);
assert.equal(progress(items).percent,50);
assert.equal(effectiveStatus(items,items[0]),'Bloqueado');
assert.equal(effectiveStatus(items,items[2]),'Bloqueado');
const done=items.map(v=>v.id==='child'?{...v,status:'Terminado'}:v);
assert.equal(progress(done).percent,100);
assert.equal(effectiveStatus(done,done[0]),'Terminado');
const allNA=items.map(v=>({...v,status:'No aplica'}));
assert.equal(progress(allNA).applicable,0);
assert.equal(progress(allNA).percent,0);
assert.equal(effectiveStatus(allNA,allNA[0]),'No aplica');
assert.equal(progress([]).percent,0);
assert.equal(descendants(items,'stage').length,4);
assert.equal(depthOf(items,'child'),3);
const moved=moveSibling(items,'branch',-1);
assert.deepEqual(moved.filter(v=>v.parent_id==='stage').map(v=>v.id),['branch','finished']);
assert.deepEqual(moved.find(v=>v.id==='child'),items.find(v=>v.id==='child'));
assert.equal(checklistTemplate.length,8);
assert.equal(checklistTemplate.reduce((n,v)=>n+v.tasks.length,0),64);
console.log('Dashboard calculations passed: leaves, exclusions, hierarchy, progress, ordering and 64-task template.');
