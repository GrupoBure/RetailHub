alter table public.rh_provider_pending add column sort_order bigint generated by default as identity;
with ranks as (
 select id,row_number() over(order by updated_at desc,id) as n,count(*) over() as total
 from public.rh_provider_pending
)
update public.rh_provider_pending p set sort_order=ranks.total-ranks.n+1 from ranks where p.id=ranks.id;
select setval(pg_get_serial_sequence('public.rh_provider_pending','sort_order'),coalesce(max(sort_order),0)+1,false) from public.rh_provider_pending;

create function public.rh_move_provider_pending(p_provider uuid,p_section text,p_item uuid,p_completed boolean,p_direction text)
returns boolean language plpgsql set search_path = '' as $$
declare
 current_row public.rh_provider_pending%rowtype;
 neighbor public.rh_provider_pending%rowtype;
begin
 if p_direction not in ('up','down') then return false; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_provider::text||':'||p_section,0));
 select * into current_row from public.rh_provider_pending
 where id=p_item and provider_id=p_provider and section=p_section and (completed_at is not null)=p_completed for update;
 if not found then return false; end if;
 select * into neighbor from public.rh_provider_pending
 where provider_id=p_provider and section=p_section and (completed_at is not null)=p_completed
 and ((p_direction='up' and sort_order>current_row.sort_order) or (p_direction='down' and sort_order<current_row.sort_order))
 order by case when p_direction='up' then sort_order end asc,case when p_direction='down' then sort_order end desc
 limit 1 for update;
 if not found then return false; end if;
 update public.rh_provider_pending set sort_order=case when id=p_item then neighbor.sort_order else current_row.sort_order end
 where id in (p_item,neighbor.id);
 return true;
end;
$$;
revoke all on function public.rh_move_provider_pending(uuid,text,uuid,boolean,text) from public, anon, authenticated;
grant execute on function public.rh_move_provider_pending(uuid,text,uuid,boolean,text) to service_role;
